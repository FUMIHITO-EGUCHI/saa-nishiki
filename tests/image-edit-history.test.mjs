import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import { createWorkflowStore } from '../scripts/main/workflowStore.js';
import { createImageEditor } from '../scripts/main/imageEditService.js';
const url = b => `data:image/png;base64,${b.toString('base64')}`;
test('the library reopens the same source project after restart, but a replaced source starts a new one', async t => {
    const root=fs.mkdtempSync(path.join(os.tmpdir(),'saa-library-edits-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
    const store=createWorkflowStore(root),editor=createImageEditor(store);
    const original=await sharp({create:{width:16,height:16,channels:3,background:'red'}}).png().toBuffer();
    const replacement=await sharp({create:{width:16,height:16,channels:3,background:'blue'}}).png().toBuffer();
    const source={resume:true,sourceKey:'file:c:/images/original.png'};
    const first=await editor.create(url(original),'original',undefined,source);
    const reopened=createImageEditor(createWorkflowStore(root));
    assert.equal((await reopened.create(url(original),'original',undefined,source)).id,first.id);
    assert.notEqual((await reopened.create(url(replacement),'original',undefined,source)).id,first.id);
    assert.notEqual((await reopened.create(url(original),'copy',undefined,{...source,sourceKey:'file:c:/images/copy.png'})).id,first.id);
    assert.deepEqual(store.image('projects',first.id,'original.png'),original);
});
test('candidate, accept, branch, discard and failure preserve the parent across restart', async t => {
    const root=fs.mkdtempSync(path.join(os.tmpdir(),'saa-edits-')); t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
    const store=createWorkflowStore(root);
    const image=await sharp({create:{width:16,height:16,channels:3,background:'red'}}).png().toBuffer();
    const white=await sharp({create:{width:16,height:16,channels:3,background:'white'}}).png().toBuffer();
    const editor=createImageEditor(store,{ generate:async()=>({runId:'run',result:Promise.resolve({image:white})}) });
    const project=await editor.create(url(image),'test'); const original=project.currentRevision;
    const request={projectId:project.id,parentId:original,mask:url(white),lock:null,settings:{},padding:0,feather:0};
    const candidate=await editor.generate(request);
    assert.equal(store.read('projects',project.id).currentRevision,original);
    editor.accept(project.id,candidate.id);
    const reopened=createImageEditor(createWorkflowStore(root),{});
    assert.equal(reopened.get(project.id).currentRevision,candidate.id);
    reopened.select(project.id,original);
    const other=await editor.generate(request); editor.discard(project.id,other.id);
    assert.equal(editor.get(project.id).currentRevision,original);
    assert.equal(editor.get(project.id).revisions.length,3);
    const failing=createImageEditor(store,{generate:async()=>{throw new Error('OOM');}});
    await assert.rejects(failing.generate(request),/OOM/);
    assert.equal(editor.get(project.id).currentRevision,original);
    assert.equal(editor.get(project.id).attempts.at(-1).status,'failed');
    assert.deepEqual(store.image('projects',project.id,'original.png'),image);
});

test('a storage failure releases the editor for a later attempt', async t => {
    const root=fs.mkdtempSync(path.join(os.tmpdir(),'saa-edits-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
    const store=createWorkflowStore(root);
    const image=await sharp({create:{width:16,height:16,channels:3,background:'red'}}).png().toBuffer();
    const white=await sharp({create:{width:16,height:16,channels:3,background:'white'}}).png().toBuffer();
    const editor=createImageEditor(store,{generate:async()=>({runId:'run',result:Promise.resolve({image:white})})});
    const project=await editor.create(url(image));
    const request={projectId:project.id,parentId:project.currentRevision,mask:url(white),settings:{},padding:0,feather:0};
    const write=store.write;store.write=()=>{throw new Error('Disk full');};
    await assert.rejects(editor.generate(request),/Disk full/);
    store.write=write;
    assert.equal((await editor.generate(request)).status,'review');
});
